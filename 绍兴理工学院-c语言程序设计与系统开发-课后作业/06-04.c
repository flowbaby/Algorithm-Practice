// 公鸡5文钱一只，母鸡3文钱一只，小鸡3只一文钱，用100文钱买一百只鸡，其中公鸡，母鸡，小鸡都必须要有。

// 问：公鸡，母鸡，小鸡要买多少只刚好凑足100文钱。
#include <stdio.h>

int main()
{
    for (int i = 1; i <= 20; i++) {
        for (int j = 1; j <= 33; j++) {
            int k = 100 - i - j;
            if (k > 0 && k % 3 == 0 && i * 5 + j * 3 + k / 3 == 100) {
                printf("%d公鸡，%d母鸡，%d小鸡刚好凑足100文钱。\n", i, j, k);
            }
        }
    }

    return 0;
}
